"""PARITY GATE: the ported inference path must reproduce the original repo's
predictions bit-for-bit (within tolerance) on a frozen 8-frame fixture.

This is the red/green signal for every Phase-1 port task. It is RED now because
``dlofeel_state.engine.evaluate`` does not exist yet; it turns GREEN once the
inference path (engine + model + dataset) is ported and produces predictions
matching ``tests/fixtures/parity/golden_preds.h5`` (generated by the ORIGINAL
``dlopredict`` repo, so the target is fixed before any code is ported).

Calling convention preserved from the original ``simplepredict.evaluate``:
``evaluate(data_root, config, ckpt_path, out_dir=..., batch_size=...)`` where the
config DICT carries ``norm_stats_path`` / ``blank_ref_root`` / ``use_blank_ref``
and the run writes ``<out_dir>/<ckpt-parent-name>/preds_gts.h5``.

Run (parity executor): set ``DLOFEEL_PARITY_CKPT`` to the original k16 ``best.pt``
before invoking pytest. Without it the test skips (the fixture is committed but
the 137 MB checkpoint is not).
"""

import os

import h5py
import numpy as np
import pytest
import yaml

FIX = os.path.join(os.path.dirname(__file__), "fixtures", "parity")
CKPT = os.environ.get("DLOFEEL_PARITY_CKPT")


@pytest.mark.skipif(
    not CKPT,
    reason="set DLOFEEL_PARITY_CKPT to the original k16 best.pt to run the parity gate",
)
def test_parity_matches_golden(tmp_path):
    # Imported here (not at module top) so the skip path never touches the not-yet-
    # ported package. When CKPT is set this raises ModuleNotFoundError until Phase 1
    # ports the engine -- that is the intended RED state of this gate.
    from dlofeel_state.engine.evaluate import evaluate

    # The k16 architecture/preproc knobs live in the committed checkpoint config.
    with open(os.path.join(FIX, "config.yaml")) as f:
        config = yaml.safe_load(f)

    # Repoint the two path-valued keys at the self-contained fixture copies so the
    # run needs no original-repo cwd. Every other key defines k16 and is left as-is.
    config["norm_stats_path"] = os.path.join(FIX, "norm_stats.yaml")
    config["blank_ref_root"] = os.path.join(FIX, "blank_refs")

    # Blank the Sparsh DINO pretrained path: it points at a file the new repo does
    # not ship, and best.pt supplies every ViT weight via the strict load, so the
    # final model is identical. pos_embed_fn is 'learned' in the k16 config, so no
    # checkpoint inference is needed either.
    config["model_params"]["image_backbone"]["pretrained_weights_path"] = ""

    # Pin full FP32 to match the golden's numerical regime. The golden was generated
    # under torch 2.10.0+cu128; this venv is torch 2.13.0+cu130, whose default enables
    # cuDNN TF32 for convolutions (the Sparsh ViT patch-embed conv), perturbing preds
    # by ~4e-5. Disabling TF32 reproduces the golden to ~3e-8 -- an apples-to-apples
    # comparison across the toolchain drift, NOT a relaxation of the 1e-5 tolerance.
    import torch
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False

    evaluate(
        data_root=os.path.join(FIX, "samples"),
        config=config,
        ckpt_path=CKPT,
        out_dir=str(tmp_path),
        batch_size=8,
    )

    # evaluate() writes to <out_dir>/<ckpt-parent-name>/preds_gts.h5, so glob for it.
    produced = sorted(tmp_path.glob("**/preds_gts.h5"))
    assert produced, f"evaluate() wrote no preds_gts.h5 under {tmp_path}"
    new_h5 = produced[0]

    golden_path = os.path.join(FIX, "golden_preds.h5")
    with h5py.File(golden_path) as g, h5py.File(new_h5) as n:
        golden_preds = g["preds"][:]
        new_preds = n["preds"][:]
        golden_gts = g["gts"][:]
        new_gts = n["gts"][:]

    # Compare predictions only. sample_paths are ABSOLUTE and vary by machine, so
    # they are deliberately excluded from the parity assertion.
    assert golden_preds.shape == new_preds.shape, (
        f"preds shape mismatch: golden {golden_preds.shape} vs new {new_preds.shape}"
    )
    assert np.allclose(golden_preds, new_preds, atol=1e-5), (
        f"preds diverge from golden: max abs diff "
        f"{np.abs(golden_preds - new_preds).max():.2e} (atol=1e-5)"
    )

    # gts come straight from the fixture data, so parity here catches loader drift.
    assert golden_gts.shape == new_gts.shape, (
        f"gts shape mismatch: golden {golden_gts.shape} vs new {new_gts.shape}"
    )
    assert np.allclose(golden_gts, new_gts, atol=1e-5), (
        f"gts diverge from golden: max abs diff "
        f"{np.abs(golden_gts - new_gts).max():.2e} (atol=1e-5)"
    )
